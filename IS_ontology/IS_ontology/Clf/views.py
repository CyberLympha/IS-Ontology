"""
Модуль предназначен для классификации текстов из HTML-документов и сохранения их в базе данных.

Основные функции:
- Загрузка и обработка текста с веб-страницы;
- Проверка наличия статьи в базе данных и её добавление при отсутствии;
- Классификация текста с использованием обученной нейросети;
- Хранение последних обработанных URL для каждого пользователя.

Применение:
- Модуль используется в веб-приложении для анализа и классификации текстов с веб-страниц.
- В случае успешной классификации текст добавляется в базу данных, что позволяет дальнейшую работу с ним через графовую модель.
"""

import os

from django.core.handlers.wsgi import WSGIRequest
from django.shortcuts import render
import requests
import re
from bs4 import BeautifulSoup
import pickle
from tensorflow.keras.models import Sequential
from tensorflow.keras.layers import Dense, Embedding, LSTM
from tensorflow.keras.preprocessing.sequence import pad_sequences
from django.conf import settings
import pickle

from ..Ie.graph_repositories import SourceRepository
from ..Notes.models import Source, Text

# Путь к токенизатору
tokenizer_path = os.path.join(str(settings.BASE_DIR), "tokenizer.pickle")

# Путь к обученной модели
model_path = os.path.join(str(settings.BASE_DIR), "clf_is.h5")
print(model_path)

# Загрузка токенизатора из файла
with open(tokenizer_path, "rb") as handle:
     tokenizer = pickle.load(handle)

# Инициализация нейросетевой модели
classifier = Sequential()
classifier.add(Embedding(20000, 64, input_length=400)) # Входной слой
classifier.add(LSTM(64)) # LSTM слой
classifier.add(Dense(1, activation="sigmoid")) # Выходной слой с сигмоидной активацией

# Компиляция модели
classifier.compile(
    optimizer="adam", loss="binary_crossentropy", metrics=["AUC", "accuracy"]
)

# Загрузка весов модели
classifier.load_weights(model_path)

# Словарь для хранения последних URL пользователей
last = {}


def index(request: WSGIRequest):
    """
    Обрабатывает запросы GET и POST для классификации статьи и добавления её в базу данных.

    Параметры:
        request (WSGIRequest): Объект запроса, содержащий данные о запросе клиента.

    Возвращает:
        HttpResponse: Отрендеренный шаблон 'clf.html' с контекстными данными.

    Логика работы:
        - При GET запросе — инициализирует контекст без показа результата классификации.
        - При POST запросе с ключом 'classify' — выполняет классификацию статьи по URL.
        - При POST запросе с ключом 'add_to_base' — добавляет статью в базу данных с указанным описанием.
    """
    context = {} # Инициализация контекста для передачи данных в шаблон.
    global last  # Глобальная переменная для хранения последнего обработанного URL.

    # Обработка GET-запроса
    if request.method == "GET":
        # По умолчанию не отображаем результаты классификации
        context["show_verdict"] = False
        context["show"] = False 

    # Обработка POST-запроса для классификации статьи
    if request.method == "POST" and "classify" in request.POST:
        last_url = request.POST.get("request_url") # Извлекаем URL из формы

        # Проверяем валидность URL
        if check_url(last_url):
            # Проверяем наличие текста на странице
            if check_text(get_parsed_html(last_url)):
                # Выполняем классификацию статьи
                result = predict(tokenizer, classifier, last_url)
                context["request_type"] = result
                context["show"] = True
                last[request.user] = last_url # Сохраняем URL для текущего пользователя
            else:
                # Если текста нет — сообщаем об этом
                context["request_type"] = "Не удалось спарсить текст."

    # Обработка POST-запроса для добавления статьи в базу
    if request.method == "POST" and "add_to_base" in request.POST:
        description = request.POST.get("request_description") # Извлекаем описание
        url = last[request.user]  # Получаем последний URL для текущего пользователя

        # Проверяем и добавляем источник в базу
        verdict = check_source(url, description, request.user.pk)
        context["verdict"] = verdict[0]
        context["description"] = verdict[1]
        context["show_verdict"] = True

    # Возвращаем шаблон с контекстными данными
    return render(request, "clf.html", context)


def check_url(url):
    """
    Проверяет доступность указанного URL и определяет, возвращает ли он статус 404.

    Параметры:
        url (str): Ссылка на веб-страницу, которую необходимо проверить.

    Возвращает:
        bool: True — если URL доступен и не возвращает статус 404.
              False — если URL недоступен или возвращает статус 404.

    Обработка исключений:
        - requests.exceptions.SSLError: Возвращает False, если произошла ошибка SSL-сертификата.

    Логика:
        - Выполняется GET-запрос к указанному URL.
        - Если статус ответа не равен 404, возвращается True.
        - В противном случае или при ошибке SSL возвращается False.
    """
    try:
        # # Выполняем GET-запрос к URL и преобразуем ответ в строку, а псоле проверяем, что ответ не содержит статус 404
        if str(requests.get(url)) != "<Response [404]>":
            return True
        return False
    except requests.exceptions.SSLError:
        # Обработка исключения SSL-сертификата
        return False


def check_text(text):
    """
    Проверяет, содержит ли переданный текст данные.

    Параметры:
        text (str): Текст, который необходимо проверить.

    Возвращает:
        bool: True — если текст не пустой.
              False — если текст пустой.

    Логика:
        - Проверяется длина текста.
        - Если длина не равна 0, возвращается True.
        - В противном случае — False.
    """
    # Проверяем, что текст не является пустым
    if len(text) != 0:
        return True
    return False


def check_source(url: str, description: str, user) -> tuple[str, str]:
    """
    Проверяет наличие статьи по указанному URL в базе данных и добавляет её при отсутствии.

    Параметры:
        url (str): Ссылка на статью.
        description (str): Описание статьи.
        user: Идентификатор пользователя.

    Возвращает:
        tuple[str, str]: Статус операции и описание статьи.
            - "Статья уже есть в базе" и описание, если статья уже существует.
            - "Статья добавлена" и описание, если статья успешно добавлена.

    Логика:
        - Проверяется наличие статьи с данным URL в базе данных.
        - Если статья найдена, возвращается соответствующий статус и описание.
        - В противном случае создаётся новый объект Source и сохраняется в базу.
        - Создаётся объект Text с текстом статьи и сохраняется в базу.
    """
    # Проверяем наличие статьи по URL
    if Source.objects.filter(url=url):
        # Статья уже существует в базе
        return (
            "Статья уже есть в базе",
            "Описание статьи: " + str(Source.objects.filter(url=url)[0].description),
        )
    else:
        # Создание нового объекта Source
        source = Source(url=url, description=description)
        source.save()

        # Создание репозитория для источника и сохранение в
        SourceRepository(url, description, source.date, user).create()
        text = Text(source=source, text=get_parsed_html(url))
        text.save()

        # Возвращаем статус и описание
        return (
            "Статья добавлена",
            "Описание статьи: " + Source.objects.filter(url=url)[0].description,
        )


def predict(tokenizer, model, url):
    """
    Выполняет предсказание категории статьи по URL с использованием обученной модели.

    Параметры:
        tokenizer: Объект токенизатора для преобразования текста в последовательность.
        model: Обученная модель нейросети для классификации текста.
        url (str): Ссылка на статью, которую необходимо классифицировать.

    Возвращает:
        str: Сообщение с вероятностью принадлежности статьи к категории информационной безопасности.

    Логика:
        - Извлекается текст статьи по указанному URL.
        - Текст преобразуется в последовательность с помощью токенизатора.
        - Последовательность приводится к одинаковой длине методом pad_sequences.
        - Модель прогнозирует вероятность принадлежности статьи к информационной безопасности.
    """
    # Извлекаем текст статьи по URL
    text = get_parsed_html(url)

    # Преобразуем текст в последовательность индексов
    sequence = tokenizer.texts_to_sequences([text])

    # Дополняем последовательность до длины 400 символов
    sequence = pad_sequences(sequence, maxlen=400)

    # Выполняем предсказание модели
    proba = model.predict(sequence)[0][0]

    # Формируем и возвращаем результат
    return (
        "Cтатья относится к информационной безопасности с вероятностью "
        + str(proba)[:4]
    )


def get_parsed_html(link):
    """
    Извлекает текст статьи с указанного URL и очищает его от ненужных символов и тегов.

    Параметры:
        link (str): Ссылка на статью для извлечения текста.

    Возвращает:
        str: Очищенный и объединённый текст статьи.

    Логика:
        - Выполняется GET-запрос для загрузки HTML-страницы.
        - Извлекаются все абзацы (<p> теги) и проверяется их длина.
        - Очищается текст от символов \xa0 и цифр перед скобками.
        - Объединяются абзацы в один текстовый блок и возвращается результат.
    """
    # Выполняем GET-запрос для получения HTML-документа
    doc = requests.get(link)

    # Создаем объект BeautifulSoup для парсинга HTML
    soup = BeautifulSoup(doc.text, "html.parser")

    # Список для хранения очищенных абзацев
    text = []
    for p in soup.find_all("p"):
        # Проходим по каждому абзацу (<p> тегу) в HTML
        if len(p.text.split()) > 4:
            s = p.text
            # Заменяем \xa0 на пробел и удаляем цифры перед скобками
            s = s.replace("\xa0", " ")
            s = re.sub("\d\)", "", s).strip()
            text.append(s)
    # Объединяем все абзацы в один текстовый блок
    return " ".join([x for x in text])


