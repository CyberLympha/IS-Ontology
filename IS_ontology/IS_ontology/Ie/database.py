from django.conf import settings
from neo4j import GraphDatabase, BoltDriver, Session


"""
database.py

Модуль для управления подключением и выполнением запросов к базе данных Neo4j.

Содержит:
    - Инициализацию драйвера подключения к Neo4j.
    - Функции для получения сессий.
    - Функции для выполнения транзакций (чтение и запись).

Особенности:
    - Использует параметры подключения из настроек Django (settings.NEO4J_URL и settings.NEO4J_AUTH).
    - Обеспечивает автоматическое закрытие сессий после выполнения запросов.
    - Разделение операций на чтение и запись для повышения производительности и надёжности.

Замечания:
    - Требует аккуратного управления ресурсами: драйвер должен быть закрыт через close() при завершении работы приложения.
"""

# Инициализация драйвера для подключения к базе данных Neo4j
# Используются параметры подключения из настроек Django
_driver: BoltDriver = GraphDatabase.driver(settings.NEO4J_URL, auth=settings.NEO4J_AUTH)


def close():
    """
    Закрывает драйвер подключения к базе данных Neo4j.

    Описание процесса:
        - Освобождает все ресурсы, связанные с подключением к Neo4j.
        - Рекомендуется вызывать эту функцию при завершении работы приложения,
          чтобы корректно закрыть соединение с базой данных.

    Returns:
        None
    """
    _driver.close()


def get_session() -> Session:
    """
    Открывает новую сессию подключения к базе данных Neo4j.

    Описание процесса:
        - Использует ранее инициализированный драйвер (_driver).
        - Создаёт и возвращает объект сессии для выполнения транзакций.

    Returns:
        Session: Новый объект сессии для работы с базой данных Neo4j.
    """
    return _driver.session()


def execute(tf, *args, **kwargs):
    """
    Выполняет транзакцию записи в базу данных Neo4j.

    Описание процесса:
        - Открывает новую сессию через get_session().
        - Выполняет переданную функцию tf в контексте транзакции записи (write_transaction).
        - Передаёт все аргументы и именованные аргументы в функцию tf.

    Args:
        tf (Callable): Функция, которая описывает логику транзакции.
        *args: Позиционные аргументы, передаваемые в tf.
        **kwargs: Именованные аргументы, передаваемые в tf.

    Returns:
        Any: Результат выполнения транзакции (зависит от реализации tf).
    """
    # Открываем сессию и выполняем транзакцию записи
    with get_session() as session:
        return session.write_transaction(tf, *args, **kwargs)


def execute_read(tf, *args, **kwargs):
    """
    Выполняет транзакцию чтения из базы данных Neo4j.

    Описание процесса:
        - Открывает новую сессию через get_session().
        - Выполняет переданную функцию tf в контексте транзакции чтения (read_transaction).
        - Передаёт все аргументы и именованные аргументы в функцию tf.

    Args:
        tf (Callable): Функция, которая описывает логику транзакции.
        *args: Позиционные аргументы, передаваемые в tf.
        **kwargs: Именованные аргументы, передаваемые в tf.

    Returns:
        Any: Результат выполнения транзакции (зависит от реализации tf).
    """
    # Открываем сессию и выполняем транзакцию чтения
    with get_session() as session:
        return session.read_transaction(tf, *args, **kwargs)



